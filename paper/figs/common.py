"""Shared helpers: paths, intervals, and the generated-numbers writer.

Every number printed into the paper goes through `Macros.add`, which writes a
LaTeX macro together with a comment naming the source file it was read from.
"""
import json
import math
import random
import re
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent
DATA = PAPER / "data"
GEN = PAPER / "generated"
FIGS = PAPER / "figs"
GEN.mkdir(exist_ok=True)


def load(rel):
    return json.loads((DATA / rel).read_text())


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    den = 1 + z * z / n
    c = (p + z * z / (2 * n)) / den
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (c - h, c + h)


def cluster_bootstrap(groups, stat, reps=2000, seed=20261107):
    """Percentile CI of `stat(list_of_items)` resampling whole clusters (contexts or tasks)."""
    rng = random.Random(seed)
    keys = list(groups)
    vals = []
    for _ in range(reps):
        items = []
        for k in (rng.choice(keys) for _ in keys):
            items.extend(groups[k])
        vals.append(stat(items))
    vals.sort()
    return vals[int(0.025 * reps)], vals[int(0.975 * reps) - 1]


def tex_escape(s):
    return str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


class Macros:
    """Collects \\newcommand definitions; each line carries its source as a comment."""

    def __init__(self, name):
        self.name = name
        self.lines = [f"% AUTO-GENERATED by figs/{name}.py -- do not edit by hand."]

    def add(self, key, value, source):
        assert key.isalpha(), key
        # A bare "-" prints as a hyphen in text mode; \ensuremath{-} is a minus in text and math.
        value = re.sub(r"^-(?=[0-9.])", r"\\ensuremath{-}", str(value))
        self.lines.append(f"\\newcommand{{\\{key}}}{{{value}}} % source: {source}")

    def write(self):
        (GEN / f"num_{self.name}.tex").write_text("\n".join(self.lines) + "\n")


def write_table(name, body, script):
    (GEN / f"tab_{name}.tex").write_text(f"% AUTO-GENERATED by figs/{script}.py -- do not edit by hand.\n" + body)


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}"


