#!/usr/bin/env python3
"""FRESH-115: the OSWorld tasks no run of this project has read, kept for one confirmatory shot (docs/FRESH_REGISTRATION.md).

Recomputes from repository files only: (1) DIAG and TEST regenerated from src/osworld/test_nogdrive.json by the frozen
rule of src/osworld/make_split.py equal the committed split files; (2) the 121 tasks in neither split; (3) minus every
task that a project file names (reproduce/results/unsplit_task_reads.json, written on the project's server by
reproduce/tools/scan_task_reads.py); (4) the list and its sha256 equal docs/FRESH_TASKS.json.
Standard library only; exit 1 on any mismatch. `--write` rewrites docs/FRESH_TASKS.json (maintainers only).
"""
import hashlib
import json
import pathlib
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
ROOT = pathlib.Path(__file__).resolve().parent.parent
OSW = ROOT / "src/osworld"
OUT = ROOT / "docs/FRESH_TASKS.json"
NOGDRIVE_SHA256 = "fcb9497e93a8986407345d3012c872c9c2fed253420730fbea64ccfcace67dbb"
SPLIT_SHA1 = {"split_diag.json": "51e670b3", "split_test.json": "957d68e7"}


def fresh():
    nog = OSW / "test_nogdrive.json"
    assert hashlib.sha256(nog.read_bytes()).hexdigest() == NOGDRIVE_SHA256, "test_nogdrive.json changed"
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, "-B", str(OSW / "make_split.py"), str(nog), tmp], check=True, capture_output=True)
        for name, sha1 in SPLIT_SHA1.items():
            regen, committed = json.loads((pathlib.Path(tmp) / name).read_text()), json.loads((OSW / name).read_text())
            assert regen == committed, f"{name}: the frozen rule does not reproduce the committed split"
            assert hashlib.sha1((OSW / name).read_bytes()).hexdigest().startswith(sha1), f"{name}: sha1 differs from the journal"
    meta = json.loads(nog.read_text())
    used = {i for n in SPLIT_SHA1 for v in json.loads((OSW / n).read_text()).values() for i in v}
    unsplit = sorted(f"{d}/{i}" for d, ids in meta.items() for i in ids if i not in used)
    scan = json.loads((ROOT / "reproduce/results/unsplit_task_reads.json").read_text())
    assert sorted(scan["tasks"]) == unsplit, "the scan does not cover exactly the unsplit tasks"
    read = sorted(t for t, h in scan["tasks"].items() if h["result_dirs"] or h["files"])
    tasks = [t for t in unsplit if t not in read]
    text = "\n".join(tasks) + "\n"
    dom = {}
    for t in tasks:
        dom[t.split("/")[0]] = dom.get(t.split("/")[0], 0) + 1
    return {"name": f"FRESH-{len(tasks)}",
            "definition": "tasks of src/osworld/test_nogdrive.json (RealtimeGUI @ a763361, 361 tasks) in neither DIAG nor "
                          "TEST, minus every task named by a project file in reproduce/results/unsplit_task_reads.json",
            "n_all": sum(map(len, meta.values())), "n_diag": 120, "n_test": 120, "n_unsplit": len(unsplit),
            "excluded_as_read": read, "scan_utc": scan["scanned_utc"], "n": len(tasks),
            "sha256_of_task_list": hashlib.sha256(text.encode()).hexdigest(),
            "sha256_note": "sha256 of the sorted 'domain/task_id' lines below, joined by newlines, with a final newline",
            "domains": dict(sorted(dom.items(), key=lambda kv: (-kv[1], kv[0]))), "tasks": tasks}


def main():
    got = fresh()
    if "--write" in sys.argv:
        OUT.write_text(json.dumps(got, indent=1) + "\n")
    ref = json.loads(OUT.read_text())
    ok = ref == got
    print(f"OSWorld test_nogdrive {got['n_all']} tasks = DIAG {got['n_diag']} + TEST {got['n_test']} + unsplit {got['n_unsplit']}"
          " (splits regenerated by the frozen rule: identical)")
    print(f"unsplit tasks named by a project file (pilot runs): {len(got['excluded_as_read'])}")
    print(f"{got['name']}: {got['n']} tasks, sha256 {got['sha256_of_task_list']}")
    print("  domains: " + ", ".join(f"{k} {v}" for k, v in got["domains"].items()))
    print(("  OK  " if ok else "  FAIL ") + "equals docs/FRESH_TASKS.json")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
